'use client';

import { useEffect } from 'react';
import Link from 'next/link';
import { ArrowLeft, BrainCircuit, MessageCircle, ShieldCheck } from 'lucide-react';
import { AIProvider, useAIContext } from '@/contexts/AIContext';
import AITutorDrawer from '@/components/ai/AITutorDrawer';

function launchAssistant() {
  window.dispatchEvent(new CustomEvent('zeis:open-ai-assistant'));
}

function AgentWorkspace({ available, mode }: { available: boolean; mode: 'student' | 'teacher' }) {
  const { setMode } = useAIContext();

  useEffect(() => {
    setMode(mode);
    if (available) launchAssistant();
  }, [available, mode, setMode]);

  return (
    <main className="landing-shell min-h-screen px-5 py-8 text-slate-100 sm:px-8 sm:py-12">
        <div className="mx-auto max-w-5xl">
          <header className="flex items-center justify-between">
            <Link href="/" className="flex items-center gap-2 text-sm font-bold tracking-[0.16em] text-white"><span className="brand-mark !h-9 !w-9 !rounded-xl !text-base">Z</span> ZEIS</Link>
            <Link href="/" className="rounded-xl border border-white/10 px-4 py-2 text-xs text-slate-300 transition hover:border-cyan-300/40 hover:text-cyan-100">Home</Link>
          </header>
          <section className="mt-12 rounded-[2rem] border border-cyan-200/15 bg-slate-900/55 p-6 backdrop-blur-xl sm:mt-16 sm:p-10">
            <p className="inline-flex items-center gap-2 text-[10px] font-semibold uppercase tracking-[0.22em] text-cyan-300"><BrainCircuit aria-hidden="true" className="h-4 w-4" /> ZEIS intelligence</p>
            <h1 className="mt-4 text-4xl font-semibold tracking-tight text-white sm:text-5xl">Zanzibar AI Agent</h1>
            <p className="mt-5 max-w-3xl text-sm leading-7 text-slate-300 sm:text-base">
              Ask for a clear explanation, get study guidance, or explore an idea with the ZEIS AI Tutor. Responses are generated by the connected ZEIS AI service.
            </p>
            {available ? (
              <>
                <button type="button" onClick={launchAssistant} className="primary-cta mt-8"><MessageCircle aria-hidden="true" className="h-4 w-4" />Open AI Tutor</button>
                <p className="mt-5 flex items-center gap-2 text-xs text-slate-400"><ShieldCheck aria-hidden="true" className="h-4 w-4 text-cyan-300" />Sign-in and school permissions are verified by ZEIS.</p>
                <AITutorDrawer />
              </>
            ) : (
              <div role="status" className="mt-8 rounded-2xl border border-amber-300/20 bg-amber-950/25 p-5 text-sm leading-6 text-amber-100">
                The AI Tutor needs a school assignment on your ZEIS profile before it can securely access learning context. Please contact your school administrator.
              </div>
            )}
            <Link href="/" className="secondary-cta mt-8"><ArrowLeft aria-hidden="true" className="h-4 w-4" />Back to ZEIS</Link>
          </section>
        </div>
    </main>
  );
}

export default function AgentLauncher({ available, mode }: { available: boolean; mode: 'student' | 'teacher' }) {
  return <AIProvider><AgentWorkspace available={available} mode={mode} /></AIProvider>;
}
